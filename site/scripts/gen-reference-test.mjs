// Runs the real generator, with the program SITE_BIN_DIR names, on a copy of the site: write mode
// keeps every hand-written page, and --check still catches a stale or out-of-date generated page.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const repo = path.resolve('..');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'gen-reference-'));
const site = path.join(root, 'site');
const out = path.join(site, 'src/content/docs/reference');
const redirectsFile = path.join(site, 'src/data/redirects.json');
const LINKED = ['node_modules', 'examples'];

const generate = (...args) => spawnSync(process.execPath, ['scripts/gen-reference.mjs', ...args], { cwd: site, encoding: 'utf8' });
const passes = (...args) => {
  const r = generate(...args);
  assert.equal(r.status, 0, r.stderr);
};
const reports = (text) => {
  const r = generate('--check');
  assert.equal(r.status, 1, r.stdout);
  assert.match(r.stderr, text);
};
const folder = () => Object.fromEntries(fs.readdirSync(out, { recursive: true, withFileTypes: true })
  .filter((f) => f.isFile())
  .map((f) => path.join(f.parentPath, f.name))
  .map((p) => [path.relative(out, p), fs.readFileSync(p, 'utf8')]));

try {
  for (const input of ['schemas', 'scripts/release_install.py', 'docs/resource-observations.md', 'crates/thinkthen/src']) {
    fs.cpSync(path.join(repo, input), path.join(root, input), { recursive: true });
  }
  fs.cpSync(path.resolve('.'), site, { recursive: true, filter: (p) => !LINKED.includes(path.relative(path.resolve('.'), p)) && path.basename(p) !== 'dist' });
  for (const name of LINKED) fs.symlinkSync(path.resolve(name), path.join(site, name));

  // Write mode changes nothing here, including a new page the menu does not list yet.
  fs.writeFileSync(path.join(out, 'draft.mdx'), 'A page in progress.\n');
  const before = folder();
  for (const name of ['json-output.mdx', 'options.mdx', 'release-notes.mdx', 'troubleshooting.mdx']) assert.ok(before[name], name);
  passes();
  assert.deepEqual(folder(), before);
  fs.rmSync(path.join(out, 'draft.mdx'));
  passes('--check');

  // A generated page left behind at a retired address, or beside the hand-written page of its address.
  for (const name of ['rows.md', 'options.md']) {
    fs.writeFileSync(path.join(out, name), 'Left behind.\n');
    reports(new RegExp(`${name}: not generated by this build`));
    fs.rmSync(path.join(out, name));
  }

  // An address nothing else claims still gets its generated page, and --check still compares it.
  const redirects = JSON.parse(fs.readFileSync(redirectsFile, 'utf8'));
  delete redirects['/reference/rows/'];
  fs.writeFileSync(redirectsFile, JSON.stringify(redirects));
  reports(/rows\.md: differs from the build/);
  passes();
  assert.match(folder()['rows.md'], /Written by scripts\/gen-reference\.mjs/);
  passes('--check');
  fs.appendFileSync(path.join(out, 'rows.md'), '\nEdited by hand.\n');
  reports(/rows\.md: differs from the build/);
  console.log('gen-reference: hand-written pages kept; stale and out-of-date pages reported');
} finally {
  fs.rmSync(root, { recursive: true, force: true });
}
